def payout(reg, prem, comp, psyc, exp):
    rev = reg + prem + comp + psyc
    z = 2465 * 10.5 + 1465 * 1.5 + RATE * (prem + comp + psyc)
    bare = compute(rev, 0.0)["total"]
    marg = (compute(rev + 1000, 0.0)["total"] - bare) / 1000
    gap = bare - z
    return (gap / (1 - marg) if gap > 0 else 0.0), rev


