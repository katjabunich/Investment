def _comp_with_raise(raise_year: float, expenses: float) -> float:
    """Компенсация с грос-апом: она входит в выручку и облагается сама."""
    comp = 0.0
    for _ in range(60):
        tax = compute(102_836 + raise_year + comp, expenses)["total"]
        comp = max(0.0, tax - Z_EMBEDDED)
    return comp


def _raise_headroom(expenses: float) -> float:
    lo, hi = 0.0, 40_000.0
    for _ in range(70):
        mid = (lo + hi) / 2
        if _comp_with_raise(mid, expenses) < 10_000:
            lo = mid
        else:
            hi = mid
    return lo


