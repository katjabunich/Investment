#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Верификация данных о доходах и расходах: сходимость, арифметика, пересечения.

Проверяет не «правильность» исходных цифр (их даёт выписка), а то, что все
производные величины сходятся между собой и с config/cashflow.yaml. Любое
расхождение печатается как FAIL с числами — молча ничего не подгоняется.

    python3 tools/verify.py
"""

from __future__ import annotations

import sys

OK, FAIL = [], []


def check(name: str, got: float, want: float, tol: float = 1.0, unit: str = "EUR") -> None:
    if abs(got - want) <= tol:
        OK.append(f"  [ok]   {name}: {got:,.2f} {unit}".replace(",", " "))
    else:
        FAIL.append(f"  [FAIL] {name}: получено {got:,.2f}, ожидалось {want:,.2f} "
                    f"(расхождение {got - want:+,.2f} {unit})".replace(",", " "))


def note(text: str) -> None:
    OK.append(f"  [--]   {text}")


# ---------------------------------------------------------------------------
# 1. РАСХОДЫ: сумма категорий против измеренного итога
# ---------------------------------------------------------------------------
# Косметика по протоколу от розацеи учтена в МЕДИЦИНЕ, а не в красоте:
# это лечение хронического состояния. В «красоте» остался парикмахер.
CATEGORIES = {
    "партнёру": 600, "психолог": 600, "медицина": 229, "одежда": 187,
    "кафе и рестораны": 185, "страховки": 166, "парикмахер": 145,
    "подписки и софт": 137, "поездки (брони, нетто)": 130,
    "досуг и развлечения": 105, "дом и обустройство": 95, "спорт": 85,
    "онлайн-покупки": 73, "транспорт и связь": 55,
    "прочее и неразнесённое": 188,
}
EXPENSES_TOTAL = 2980
check("сумма категорий = итог расходов", sum(CATEGORIES.values()), EXPENSES_TOTAL, tol=0)

# ---------------------------------------------------------------------------
# 2. РАСХОДЫ: помесячный ряд против среднего
# ---------------------------------------------------------------------------
MONTHLY = {  # возвраты отнесены к месяцу покупки
    "сен 2025": 2192, "окт 2025": 2425, "ноя 2025": 2604, "дек 2025": 2379,
    "янв 2026": 2208, "фев 2026": 2193, "мар 2026": 1896, "апр 2026": 2630,
    "май 2026": 2646, "июн 2026": 2261, "июл 2026": 1736,
}
avg_abn = sum(MONTHLY.values()) / len(MONTHLY)
check("среднее по ABN за 11 месяцев", avg_abn, 2288, tol=2)

# сборка итога из среднего по ABN
build = (avg_abn
         + 600      # психолог с делового счёта
         + 154      # Wise
         + 130      # прочие личные траты с делового счёта
         + 41       # партнёру фиксировано 600 вместо измеренных 559
         - 104      # ZVW — компенсирует клиент
         - 49       # спорт: база несёт 220 за 4 мес 2025, сейчас 85
         - 78)      # разовая медицина 853 за 11 мес
check("сборка итога из среднего ABN", build, EXPENSES_TOTAL, tol=8)

# ---------------------------------------------------------------------------
# 3. ПОЕЗДКИ: валовые, возвраты, нетто
# ---------------------------------------------------------------------------
TRAVEL_2026 = [98.00, 196.14, 232.99, 570.44, 2.99, 431.51, 173.84, 124.74,
               522.00, 68.63]
COMP_2026 = [190.00, 200.00, 200.00, 125.00, 125.00, 125.00, 150.00, 7.50,
             480.00, 125.00, 35.00]
TRAVEL_2025, COMP_2025 = 1941.79, 1169.00

gross = sum(TRAVEL_2026) + TRAVEL_2025
comp = sum(COMP_2026) + COMP_2025
net = gross - comp
check("поездки: валовые за 11 мес", gross, 4363, tol=1)
check("поездки: возвраты за 11 мес", comp, 2932, tol=1)
check("поездки: нетто в месяц", net / 11, 130, tol=1)
check("доля возврата 2026", sum(COMP_2026) / sum(TRAVEL_2026) * 100, 73, tol=1, unit="%")
if sum(COMP_2026) > sum(TRAVEL_2026):
    FAIL.append("  [FAIL] возвраты 2026 превышают валовые брони — привязка неверна")
else:
    note(f"возвраты 2026 ({sum(COMP_2026):.0f}) не превышают валовые "
         f"({sum(TRAVEL_2026):.0f}) — привязка непротиворечива")

# ---------------------------------------------------------------------------
# 4. КРАСОТА и ОДЕЖДА
# ---------------------------------------------------------------------------
HAIR = [350, 100, 300, 300, 240, 300]          # 5 визитов, ноя-25 двумя платежами
COSM = 620.29
check("парикмахер: в месяц", sum(HAIR) / 11, CATEGORIES["парикмахер"], tol=1)
check("уход по протоколу (в медицине)", COSM / 11, 56, tol=1)

ZAL_OUT = 269.80 + 985.67 + 664.28
ZAL_BACK = 189.90 + 43 + 159 + 43 + 274.84 + 236.29 + 100 + 93.99 + 53
VIP = 200 + 192 + 96 + 36
check("одежда: итого в месяц", (ZAL_OUT - ZAL_BACK + VIP + 809.27) / 11,
      CATEGORIES["одежда"], tol=1)
check("доля возврата Zalando 2026", ZAL_BACK / ZAL_OUT * 100, 62, tol=1, unit="%")

# ---------------------------------------------------------------------------
# 5. ДОХОД: реконструкция
# ---------------------------------------------------------------------------
REVENUE, TAX, BIZ_NO_PSY, SIDE = 105_236, 30_957, 4_235, 500
net_year = REVENUE - TAX - BIZ_NO_PSY
income = net_year / 12 + SIDE
check("чистый доход в месяц", income, 6337, tol=2)
note("психолог 7 200 в деловых расходах для налога, но из дохода НЕ вычтен — "
     "он стоит в личных расходах (600/мес). Двойного счёта нет")

# налог независимо, через tools/tax_zzp.py
try:
    sys.path.insert(0, "tools")
    from tax_zzp import compute  # noqa: E402
    r = compute(REVENUE, 11_435)
    check("налог по шкале (tax_zzp.py)", r["total"], TAX, tol=50)
    check("налогооблагаемая база", r["base"], 80_841, tol=50)
    if r["base"] > 79_137:
        note(f"база {r['base']:,.0f} выше порога 79 137 -> предельная ставка 49,5 %"
             .replace(",", " "))
except Exception as e:                                    # noqa: BLE001
    FAIL.append(f"  [FAIL] не удалось проверить налог через tax_zzp.py: {e}")

# ---------------------------------------------------------------------------
# 6. ПОТОК И НОРМА СБЕРЕЖЕНИЙ
# ---------------------------------------------------------------------------
free = income - EXPENSES_TOTAL
check("свободный поток", free, 3357, tol=2)
check("норма сбережений", free / income * 100, 53, tol=1, unit="%")
CONTRIB = 2700
if CONTRIB > free:
    FAIL.append(f"  [FAIL] взнос {CONTRIB} больше свободного потока {free:.0f}")
else:
    note(f"взнос {CONTRIB} помещается в поток {free:.0f}, запас {free - CONTRIB:.0f}")

# ---------------------------------------------------------------------------
# 7. ДИСКРЕЦИОННОЕ ПРОТИВ БАЗОВОГО
# ---------------------------------------------------------------------------
# Считается по ЭКОНОМИЧЕСКОЙ разноске: платёж партнёру распущен на состав
# по фактическим выпискам общих счетов (см. блок 10 и docs/joint-accounts.md).
# Рестораны в поездках вынесены из «кафе» в «поездки»: это часть стоимости
# поездки, а не повседневная статья. 89/мес = 46 общий счёт (флаг банка
# «за границей») + 43 своя карта (опознано по названиям заведений).
ECON = {"кафе и рестораны дома": 175, "одежда": 187, "парикмахер": 145,
        "поездки (брони, еда и траты в пути)": 266, "досуг и развлечения": 113,
        "онлайн-покупки": 79,
        "продукты": 186, "жильё и коммуналка": 163, "медицина": 234,
        "страховки": 166, "транспорт и связь": 84, "резерв на ремонт": 38}
disc = sum(ECON[k] for k in ["кафе и рестораны дома", "одежда", "парикмахер",
                             "поездки (брони, еда и траты в пути)",
                             "досуг и развлечения", "онлайн-покупки"])
base = sum(ECON[k] for k in ["продукты", "жильё и коммуналка", "медицина",
                             "страховки", "транспорт и связь", "резерв на ремонт"])
check("гибкое", disc, 965, tol=0)
check("обязательное", base, 871, tol=0)
note(f"дискреционное {disc} {'<' if disc < base else '>'} базового {base} "
     f"({disc / EXPENSES_TOTAL:.0%} всех расходов)")

# ---------------------------------------------------------------------------
# 8. ПОДУШКА — здесь ожидается расхождение, цель считалась от старых расходов
# ---------------------------------------------------------------------------
FUND, RESERVE_TAX, ACCOUNTS = 19_972, 19_200, 39_172
check("подушка = остатки минус резерв на налог", ACCOUNTS - RESERVE_TAX, FUND, tol=1)
check("цель подушки (6 мес x текущие расходы)", 6 * EXPENSES_TOTAL, 17_880, tol=1)
note(f"покрытие: {FUND / EXPENSES_TOTAL:.1f} месяца при цели 6, "
     f"излишек {FUND - 6 * EXPENSES_TOTAL:,.0f}".replace(",", " "))

# ---------------------------------------------------------------------------
# 9. МОДЕЛИ FIRE — допущения должны совпадать с фактом
# ---------------------------------------------------------------------------
MODEL_EXPENSES, MODEL_CONTRIB = 2980, 2700
if MODEL_EXPENSES != EXPENSES_TOTAL:
    FAIL.append(f"  [FAIL] расчёты FIRE идут от расходов {MODEL_EXPENSES}, "
                f"а факт {EXPENSES_TOTAL} "
                f"(разница {EXPENSES_TOTAL - MODEL_EXPENSES:+d}/мес)")
else:
    note(f"модель FIRE считает от фактических расходов {EXPENSES_TOTAL}")
if MODEL_CONTRIB != CONTRIB:
    FAIL.append(f"  [FAIL] расчёты FIRE идут от взноса {MODEL_CONTRIB}, "
                f"а фактический взнос {CONTRIB}")
else:
    note(f"модель FIRE считает от фактического взноса {CONTRIB}")

# ---------------------------------------------------------------------------
# 10. ОБЩИЕ СЧЕТА: разноска платежа партнёру (docs/joint-accounts.md)
# ---------------------------------------------------------------------------
# «Huis» 100/мес — резерв на крупный ремонт, то есть отложенный расход,
# а не накопления: он входит в содержание домохозяйства.
HH_FIXED, HH_VAR, HH_RES = 487.0, 846.0, 100.0
check("домохозяйство: содержание", HH_FIXED + HH_VAR + HH_RES, 1433, tol=1)
# Взносы пропорциональны доходам — так договорено; половина не эталон.
HER_IN = CATEGORIES["партнёру"]
check("взносы покрывают содержание", HER_IN + 833, HH_FIXED + HH_VAR + HH_RES, tol=1)
note("взносы пропорциональны доходам по договорённости; дом принадлежит "
     "партнёру, ипотеку по нему платит он")
note("погашение тела ипотеки 686/мес финансируется отдельно и её взноса "
     "не касается; «Huis» — резерв на ремонт, не накопления")

# разложение 600 по факту общих счетов
SPLIT = {"продукты": 203, "жильё и коммуналка": 178, "кафе вместе": 82,
         "резерв на ремонт": 42, "транспорт и связь": 32, "дом": 25,
         "досуг": 9, "подписки": 7, "онлайн": 7, "прочее": 10, "медицина": 5}
check("разложение платежа партнёру", sum(SPLIT.values()), CATEGORIES["партнёру"], tol=1)
DISC_IN_SPLIT = SPLIT["кафе вместе"] + SPLIT["дом"] + SPLIT["досуг"] + SPLIT["онлайн"]
note(f"внутри взноса гибких трат ~{DISC_IN_SPLIT}/мес")
# Поездки собираются из трёх кусков; масштаб общего счёта 549/600, потому
# что 51 её взноса — адресные доплаты во время поездок, а не средний микс.
CAFE_TRIP_OWN, CAFE_TRIP_JOINT, TRIP_TOPUP = 43, 42, 51
CAFE_HOME_JOINT = SPLIT["кафе вместе"] - 46          # 82 всего − 46 за границей
check("кафе дома", (CATEGORIES["кафе и рестораны"] - CAFE_TRIP_OWN)
      + CAFE_HOME_JOINT * 549 / 600, 175, tol=2)
check("поездки целиком", CATEGORIES["поездки (брони, нетто)"] + CAFE_TRIP_OWN
      + CAFE_TRIP_JOINT + TRIP_TOPUP, 266, tol=1)
note("рестораны за границей на общем счёте 1 318/год из 1 742 всех трат "
     "за границей — 39 операций")
# доплаты в повседневный счёт совпадают с месяцами поездок
TOPUPS = {"авг": (30, 3), "сен": (200, 258), "окт": (400, 317), "ноя": (0, 401),
          "дек": (49, 0), "янв": (10, 19), "фев": (55, 0), "мар": (0, 0),
          "апр": (12, 0), "май": (150, 10), "июн": (751, 733), "июл": (0, 0)}
top_all = sum(t for t, _ in TOPUPS.values())
top_trip = sum(t for m, (t, _) in TOPUPS.items() if m in ("сен", "окт", "июн"))
check("доплаты сверх перевода с хаба за год", top_all, 1658, tol=1)
check("доля доплат в три месяца поездок", top_trip / top_all * 100, 82, tol=1, unit="%")
note("в июне доплатили 751 при тратах за границей 733 — почти евро в евро")

# ---------------------------------------------------------------------------
# 11. ПОТОЛОК ТРАТ И LIJFRENTE ИЗ ПРЕМИЙ
# ---------------------------------------------------------------------------
# Вопрос был не «что урезать», а «сколько можно тратить, не сдвигая дату».
# Потолок = доход − флэт 2 700 − взнос в lijfrente + возврат налога с него.
INCOME_NET, FLAT, LIJF_YEAR = 6337, 2700, 6000
TAX_NO_LIJF, TAX_WITH_LIJF = 30957, 28374        # tools/tax_zzp.py, шкала 2026
lijf_saving = TAX_NO_LIJF - TAX_WITH_LIJF
check("экономия налога от lijfrente 6 000", lijf_saving, 2582, tol=1)
ceiling = INCOME_NET - FLAT - LIJF_YEAR / 12 + lijf_saving / 12
check("потолок трат в месяц", ceiling, 3352, tol=1)
check("свободный ход сверх факта", ceiling - EXPENSES_TOTAL, 372, tol=1)
check("свободный ход за год", (ceiling - EXPENSES_TOTAL) * 12, 4466, tol=6)
note("расходы НИЖЕ потолка на 372/мес — сокращать нечего")
# Излишек: 657/мес премиями; с вычетом резерв под налог нужен меньше.
SURPLUS_YEAR = 7884                                # 657 × 12
check("излишек с учётом вычета", SURPLUS_YEAR + lijf_saving, 10466, tol=1)
check("остаётся на IBKR сверх флэта", SURPLUS_YEAR + lijf_saving - LIJF_YEAR,
      4466, tol=1)
check("чистая стоимость lijfrente в месяц", (LIJF_YEAR - lijf_saving) / 12,
      285, tol=1)
# Разрыв по срокам: взнос в декабре 2026, экономия приходит в июне 2027.
EF_CURRENT, EF_TARGET = 19972, EXPENSES_TOTAL * 6
have_by_dec = 657 * 5 + (EF_CURRENT - EF_TARGET)
check("накопится к декабрю 2026", have_by_dec, 5377, tol=1)
check("разрыв под полный взнос 6 000", LIJF_YEAR - have_by_dec, 623, tol=1)
note("поэтому первый взнос 4 000, с 2027 — полные 6 000 (jaarruimte 19 350)")

# ---------------------------------------------------------------------------
# 12. ИПОТЕКА ЧЕРЕЗ 7 ЛЕТ: планируемое событие, не гипотеза
# ---------------------------------------------------------------------------
PORTFOLIO_NOW, REAL_RETURN, YEARS = 187480, 0.06, 7
i, n = REAL_RETURN / 12, YEARS * 12
grown = PORTFOLIO_NOW * (1 + i) ** n
contrib_fv = FLAT * (((1 + i) ** n - 1) / i)
check("портфель 2033 — рост нынешнего", grown, 285039, tol=60)
check("портфель 2033 — будущие взносы", contrib_fv, 281000, tol=60)
check("IBKR ликвидно к 2033", grown + contrib_fv, 566039, tol=100)
lijf_pot = 0.0
for _ in range(7):                                  # взносы дек 2026..дек 2032
    lijf_pot = lijf_pot * (1 + REAL_RETURN) + LIJF_YEAR
check("lijfrente к 2033 (заперто до 68)", lijf_pot, 50363, tol=5)


def _pmt(principal: float, rate: float, years: int) -> float:
    m, months = rate / 12, years * 12
    return principal * m / (1 - (1 + m) ** -months)


HOUSE, MORT_RATE, MORT_YEARS = 500_000, 0.04, 30
for share, want_pmt, want_kk in ((0.25, 597, 6875), (0.35, 835, 9625),
                                 (0.50, 1194, 13750)):
    part = HOUSE * share
    check(f"платёж при доле {share:.0%}", _pmt(part, MORT_RATE, MORT_YEARS),
          want_pmt, tol=1)
    check(f"kosten koper 5,5 % при доле {share:.0%}", part * 0.055,
          want_kk, tol=1)
check("каждые 10 % доли в расходах",
      (_pmt(HOUSE * 0.35, MORT_RATE, MORT_YEARS)
       - _pmt(HOUSE * 0.25, MORT_RATE, MORT_YEARS)), 238, tol=8)
note("платёж номинально фиксирован: за 30 лет при инфляции 2,5 % его средняя "
     "реальная величина 590 против номинала 835 — модель завышает расход")
note("даты из tools/fire.py от 2033: доля 25 % — 2040/57, 35 % — 2042/59 "
     "(с поправкой на инфляцию платежа 2040/57), 50 % — 2045/62")

